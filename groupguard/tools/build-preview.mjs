// Refresh the standalone preview renderer from the framework checkout.
// Deployment uses the generated assets; Node and node_modules are only needed here.
import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const toolDir = dirname(fileURLToPath(import.meta.url));
const framework = resolve(process.argv[2] || resolve(toolDir, '../../../ElainaBot_v2_web'));
const assets = resolve(toolDir, '../assets');
const require = createRequire(join(framework, 'package.json'));
const { build } = require('esbuild');
const sourcePath = join(framework, 'src/utils/messageMarkdown.js');
const source = await readFile(sourcePath, 'utf8');
const hash = createHash('sha256').update(source).digest('hex');
await build({
  entryPoints: [sourcePath], outfile: join(assets, 'message-markdown.js'),
  bundle: true, format: 'esm', platform: 'browser', target: 'es2022', minify: true,
  legalComments: 'eof',
  banner: { js: `// Generated by tools/build-preview.mjs from framework src/utils/messageMarkdown.js\n// Source SHA-256: ${hash}\n// Third-party licenses: PREVIEW_LICENSES.txt` },
});

// Unwrap Vue's :deep(...) while preserving nested selectors such as :has(...).
function unwrapDeep(css) {
  return css.replace(/:deep\(/g, '\u0000').split('\u0000').map((part, index) => {
    if (!index) return part;
    let nesting = 1;
    for (let i = 0; i < part.length; i++) {
      if (part[i] === '(') nesting++;
      if (part[i] === ')' && --nesting === 0) return part.slice(0, i) + part.slice(i + 1);
    }
    throw new Error('Unbalanced :deep() in MessageContent.vue');
  }).join('');
}
const component = await readFile(join(framework, 'src/components/messages/MessageContent.vue'), 'utf8');
const style = component.match(/<style scoped>([\s\S]*?)<\/style>/)?.[1];
if (!style) throw new Error('MessageContent.vue style not found');
const variables = { border: 'line', bg2: 'surface', bg3: 'surface-soft' };
const css = unwrapDeep(style).replace(/var\(--(border|bg2|bg3)\)/g, (_, key) => `var(--${variables[key]})`);
await writeFile(join(assets, 'message-markdown.css'), `/* Generated from framework MessageContent.vue; refresh with tools/build-preview.mjs. */\n${css}`);
const licenses = [];
for (const [name, file] of [['marked', 'LICENSE'], ['dompurify', 'LICENSE']]) {
  const directory = resolve(dirname(require.resolve(name)), '..');
  const pkg = JSON.parse(await readFile(join(directory, 'package.json'), 'utf8'));
  licenses.push(`${name} ${pkg.version}\n${await readFile(join(directory, file), 'utf8')}`);
}
await writeFile(join(assets, 'PREVIEW_LICENSES.txt'), licenses.join('\n\n'));
console.log(`Preview renderer built from framework source ${hash.slice(0, 12)}.`);
